class MotionDataset(torch.utils.data.Dataset):
	"""Load raw motion records generated by ``Models/data.py``."""

	def __init__(self, path):
		self.path = Path(path)
		if not self.path.exists():
			raise FileNotFoundError(f"Motion dataset not found: {self.path}")
		if not self.path.is_dir():
			raise ValueError(f"Motion dataset must be a directory: {self.path}")

		self.files = sorted(
			file_path for file_path in self.path.rglob("*.npy")
			if not file_path.stem.endswith("_typo")
		)
		if not self.files:
			raise ValueError(f"Motion dataset directory is empty: {self.path}")

	def __len__(self):
		return len(self.files)

	def __getitem__(self, idx):
		file_path = self.files[idx]
		_, separator, label = file_path.stem.partition("_")
		if not separator or not label:
			raise ValueError(
				f"Motion record filename must contain a participant and label: {file_path}"
			)
		label = label.lower()
		if any(char not in chars for char in label):
			raise ValueError(f"Motion record has an invalid label: {file_path}")

		try:
			features = np.load(file_path, allow_pickle=False)
		except (OSError, ValueError) as exc:
			raise ValueError(f"Could not load numeric motion features from {file_path}") from exc

		if features.ndim != 2 or features.shape[0] == 0:
			raise ValueError(f"Motion record {idx} must contain at least one feature frame")
		if not np.issubdtype(features.dtype, np.number):
			raise ValueError(f"Motion record {idx} must contain numeric features")

		targets = torch.tensor([chars.index(char) for char in label], dtype=torch.long)
		return torch.from_numpy(features.astype(np.float32, copy=False)), targets, len(targets)


class TestMotionDataset(torch.utils.data.Dataset):
	"""Load the flat CSV motion records used by the legacy test dataset."""

	def __init__(self, path):
		self.path = Path(path)
		if not self.path.exists():
			raise FileNotFoundError(f"Motion dataset not found: {self.path}")

		if (files := sorted(self.path.glob("*.csv")) if self.path.is_dir() else None) is None:
			raise ValueError(f"Motion dataset directory is empty: {self.path}")
		else:
			self.files = files

	def __len__(self):
		return len(self.files)

	def __getitem__(self, idx):
		file_path = self.files[idx]
		label = re.sub(r"_\d+$", "", file_path.stem).lower()
		try:
			features = np.loadtxt(file_path, delimiter=",", skiprows=1, dtype=np.float32, ndmin=2)
		except (OSError, ValueError) as exc:
			raise ValueError(f"Could not load numeric motion features from {file_path}") from exc

		if features.ndim != 2 or features.shape[0] == 0:
			raise ValueError(f"Motion record {idx} must contain at least one feature frame")

		# blank token is at the end of the alphabet
		targets = torch.tensor([chars.index(char) for char in label], dtype=torch.long)
		return torch.from_numpy(features), targets, len(targets)

